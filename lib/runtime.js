/**
 * Where the bundled FreeLLMAPI server lives and how it is launched.
 *
 * The plugin ships its own copy of the router (`vendor/server-dist`,
 * `vendor/client-dist`, `vendor/node_modules`), so nothing here depends on a
 * checkout, a Docker daemon or a global install. This module owns the one place
 * that decision is written down: the paths, and the environment the child needs.
 *
 * @module lib/runtime
 */

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))

/** Package root (`lib/` is one level down). */
export const PACKAGE_ROOT = path.resolve(HERE, '..')

/**
 * Absolute paths the router is run from and writes to.
 *
 * The database lives under the harness home rather than inside the package:
 * reinstalling the plugin must not take the user's provider keys with it.
 */
export function runtimePaths(stateDir) {
  return {
    entry: path.join(PACKAGE_ROOT, 'vendor', 'server-dist', 'index.js'),
    clientDist: path.join(PACKAGE_ROOT, 'vendor', 'client-dist'),
    dataDir: path.join(stateDir, 'runtime'),
    dbPath: path.join(stateDir, 'runtime', 'data', 'freeapi.db'),
    envPath: path.join(stateDir, 'runtime', '.env'),
  }
}

/**
 * Make sure the router's data directory and encryption key exist.
 *
 * The server refuses to start in production without `ENCRYPTION_KEY`, and it
 * encrypts every stored provider key with it. Generating it once and keeping it
 * next to the database means a restart finds the same key, so credentials
 * written yesterday still decrypt today.
 */
export function ensureRuntime(paths) {
  fs.mkdirSync(path.dirname(paths.dbPath), { recursive: true })
  if (!fs.existsSync(paths.envPath)) {
    const key = crypto.randomBytes(32).toString('hex')
    fs.mkdirSync(path.dirname(paths.envPath), { recursive: true })
    fs.writeFileSync(paths.envPath, `ENCRYPTION_KEY=${key}\n`, { mode: 0o600 })
  }
  return paths
}

/** Is the vendored server actually present? A missing tree is a broken install. */
export function assertInstalled(paths) {
  if (!fs.existsSync(paths.entry)) {
    throw new Error(`the bundled FreeLLMAPI server is missing at ${paths.entry}; reinstall the plugin`)
  }
  if (!fs.existsSync(paths.clientDist)) {
    throw new Error(`the bundled FreeLLMAPI dashboard is missing at ${paths.clientDist}; reinstall the plugin`)
  }
  return paths
}

/**
 * Environment for the child process.
 *
 * `NODE_ENV=production` is forced: in development the server expects an
 * already-migrated database and exits, which is never what a plugin launch is.
 * `ELECTRON_RUN_AS_NODE` makes the harness's own binary behave as Node when the
 * host is the packaged desktop app, so the router runs without a system Node.
 *
 * `proxy: 'direct'` sets `NO_PROXY=*`, which the server honours by reaching
 * every provider itself. The server otherwise adopts the Windows Internet
 * Options proxy, and on a machine where that proxy cannot tunnel HTTPS every
 * completion fails with ECONNRESET while the local dashboard keeps working —
 * a failure mode that looks like "the router is broken" from the outside.
 */
export function childEnv(paths, settings, seed) {
  const target = new URL(settings.baseURL)
  const port = target.port !== '' ? target.port : '3001'
  const env = {
    ...process.env,
    ELECTRON_RUN_AS_NODE: '1',
    NODE_ENV: 'production',
    FREEAPI_ENV_PATH: paths.envPath,
    FREEAPI_DB_PATH: paths.dbPath,
    CLIENT_DIST: paths.clientDist,
    PORT: port,
    HOST: '127.0.0.1',
  }
  if (settings.proxy === 'direct') env.NO_PROXY = '*'
  // Anonymous platforms the database has never seen get their `no-key` rows on
  // this boot, through the server's own declarative config. Without them the
  // router has no platform to route to and a fresh install answers nothing.
  // An operator who set this variable themselves keeps their configuration: it
  // is the only way to reach the same knob by hand.
  const platforms = Array.isArray(seed?.missing) ? seed.missing : []
  if (platforms.length > 0 && env.FREEAPI_CONFIG_JSON === undefined) {
    env.FREEAPI_CONFIG_JSON = JSON.stringify({ keys: platforms.map((platform) => ({ platform })) })
  }
  return env
}

/**
 * Read the router's unified key straight from its database.
 *
 * The key is generated by the server on first boot and shown only in the
 * dashboard, so without this the user would have to open a browser and copy it
 * before the model lane works at all. It is a local, same-process-family read:
 * the file is the router's own and the plugin is the thing that created it.
 */
export async function readUnifiedKey(dbPath) {
  if (!fs.existsSync(dbPath)) return undefined
  let DatabaseSync
  try {
    ;({ DatabaseSync } = await import('node:sqlite'))
  } catch {
    return undefined
  }
  let db
  try {
    db = new DatabaseSync(dbPath, { readOnly: true })
    const row = db.prepare("SELECT value FROM settings WHERE key = 'unified_api_key'").get()
    const value = typeof row?.value === 'string' ? row.value.trim() : ''
    return value === '' ? undefined : value
  } catch {
    // A database mid-migration has no such table yet; the caller retries.
    return undefined
  } finally {
    try {
      db?.close()
    } catch {
      // Closing a handle we may never have opened is not an error worth raising.
    }
  }
}
